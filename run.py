#!/usr/bin/env python3
"""LaborFlow local development launcher.

Starts Docker, the Spring Boot server, the Electron desktop client, and the
Taro miniapp watch build, then keeps them running until interrupted.
"""

import base64
import os
import platform
import re
import secrets
import shutil
import signal
import socket
import subprocess
import sys
import threading
import time
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent
DESKTOP_DIR = ROOT / "clients" / "desktop"
MINIAPP_DIR = ROOT / "clients" / "miniapp"
SERVER_DIR = ROOT / "server"
ENV_FILE = ROOT / ".env"
ENV_EXAMPLE = ROOT / ".env.example"
COMPOSE_DIR = ROOT / "deploy" / "docker-laborflow"

WINDOWS = os.name == "nt"

processes: list[subprocess.Popen] = []
process_names: dict[int, str] = {}
child_failures: list[str] = []
managed_ports: set[int] = set()
shutdown_requested = False
stopping = False


class LauncherError(Exception):
    pass


failure: LauncherError | None = None
failure_event = threading.Event()


def log(message: str) -> None:
    print(f"[run] {message}", flush=True)


def fail(message: str) -> None:
    raise LauncherError(message)


def record_failure(error: BaseException) -> None:
    """Remember the first failure raised by a background waiter thread."""
    global failure
    if failure is None:
        failure = error if isinstance(error, LauncherError) else LauncherError(str(error))
    failure_event.set()


def check_failure() -> None:
    if failure is not None:
        raise failure


def run_waiter(target, *args) -> None:
    """Run a waiter body, routing any failure back to the main thread."""
    try:
        target(*args)
    except BaseException as error:  # noqa: BLE001 - forwarded to the main thread
        record_failure(error)


def node_platform() -> str:
    """Return the platform name in Node.js terms, as Electron expects."""
    if WINDOWS:
        return "win32"
    if sys.platform == "darwin":
        return "darwin"
    return "linux"


def node_arch() -> str:
    """Return the CPU architecture in Node.js terms, as Electron expects."""
    machine = platform.machine().lower()
    if machine in ("x86_64", "amd64"):
        return "x64"
    if machine in ("aarch64", "arm64"):
        return "arm64"
    if machine in ("i386", "i686", "x86"):
        return "ia32"
    return machine


def read_env_file(file_path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not file_path.exists():
        return values
    for raw_line in file_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        separator = line.index("=")
        key = line[:separator].strip()
        value = line[separator + 1 :].strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    return values


def merged_env() -> dict[str, str]:
    env = dict(os.environ)
    env.update(read_env_file(ENV_FILE))
    return env


def get_env(env: dict[str, str], name: str) -> str | None:
    if name in env:
        return env[name]
    if not WINDOWS:
        return None
    lowered = name.lower()
    for key, value in env.items():
        if key.lower() == lowered:
            return value
    return None


def set_env(env: dict[str, str], name: str, value: str) -> None:
    if WINDOWS:
        lowered = name.lower()
        for key in list(env):
            if key.lower() == lowered and key != name:
                del env[key]
    env[name] = value


def unset_env(env: dict[str, str], name: str) -> None:
    for key in list(env):
        if key == name or (WINDOWS and key.lower() == name.lower()):
            del env[key]


def random_secret(length: int) -> str:
    return base64.urlsafe_b64encode(secrets.token_bytes(length)).decode().rstrip("=")


def write_generated_env(file_path: Path) -> None:
    postgres_password = random_secret(18)
    jwt_secret = random_secret(48)
    file_path.write_text(
        "\n".join(
            [
                "SPRING_PROFILES_ACTIVE=dev",
                "POSTGRES_DB=laborflow",
                "POSTGRES_USER=laborflow",
                f"POSTGRES_PASSWORD={postgres_password}",
                "DATABASE_URL=jdbc:postgresql://localhost:5434/laborflow",
                "SERVER_PORT=8089",
                "# Dev-only random secret generated by run.py. Replace before staging/production.",
                f"JWT_SECRET={jwt_secret}",
                "BOOTSTRAP_ADMIN_USERNAME=",
                "BOOTSTRAP_ADMIN_PASSWORD=",
                "UPLOAD_DIR=./uploads",
                "FILE_STORAGE_TYPE=local",
                "",
            ]
        ),
        encoding="utf-8",
    )


def ensure_env_file() -> None:
    if ENV_FILE.exists():
        return
    if not ENV_EXAMPLE.exists():
        write_generated_env(ENV_FILE)
        log("created default .env with random dev secrets")
        return
    replacements = {
        "POSTGRES_PASSWORD": random_secret(18),
        "JWT_SECRET": random_secret(48),
    }
    patched: list[str] = []
    for raw_line in ENV_EXAMPLE.read_text(encoding="utf-8").splitlines():
        if "=" not in raw_line or raw_line.lstrip().startswith("#"):
            patched.append(raw_line)
            continue
        key = raw_line[: raw_line.index("=")].strip()
        if key in replacements:
            patched.append(f"{key}={replacements[key]}")
        else:
            patched.append(raw_line)
    while patched and patched[-1] == "":
        patched.pop()
    ENV_FILE.write_text("\n".join(patched) + "\n", encoding="utf-8")
    log("created .env from .env.example with random dev secrets")


def executable_exists(file_path: str) -> bool:
    path = Path(file_path)
    if not path.is_file():
        return False
    if WINDOWS:
        return True
    return os.access(file_path, os.X_OK)


def find_command(command: str) -> str | None:
    """Locate an executable, mirroring Node's PATH/PATHEXT resolution."""
    has_path = os.path.isabs(command) or "/" in command or "\\" in command
    if has_path:
        directories = [""]
    else:
        directories = os.environ.get("PATH", "").split(os.pathsep)
    if WINDOWS:
        configured_extensions = os.environ.get("PATHEXT", ".COM;.EXE;.BAT;.CMD").split(";")
        if os.path.splitext(command)[1]:
            extensions = [""] + configured_extensions
        else:
            extensions = configured_extensions
    else:
        extensions = [""]
    for directory in directories:
        for extension in extensions:
            if has_path:
                candidate = f"{command}{extension}"
            else:
                candidate = os.path.join(directory, f"{command}{extension}")
            if executable_exists(candidate):
                return candidate
    return None


def command_exists(command: str) -> bool:
    return find_command(command) is not None


def prepare_command(command: str, args: list[str]) -> tuple[str, list[str]]:
    if WINDOWS:
        return "cmd.exe", ["/d", "/s", "/c", command, *args]
    return command, args


def format_command(command: str, args: list[str]) -> str:
    return " ".join([command, *args])


def run_checked(
    command: str,
    args: list[str],
    cwd: Path,
    env: dict[str, str] | None = None,
) -> None:
    log(f"running: {format_command(command, args)}")
    prepared_command, prepared_args = prepare_command(command, args)
    try:
        result = subprocess.run(
            [prepared_command, *prepared_args],
            cwd=str(cwd),
            env=env,
            check=False,
        )
    except FileNotFoundError:
        fail(f"command not found: {command}")
    except OSError as error:
        fail(f"could not run {command}: {error}")
    if result.returncode != 0:
        fail(
            f"command failed with exit code {result.returncode}: "
            f"{format_command(command, args)}"
        )


def pump_output(name: str, stream, listener=None) -> None:
    if stream is None:
        return
    for raw_line in iter(stream.readline, ""):
        if not raw_line:
            break
        line = raw_line.rstrip("\r\n")
        print(f"[{name}] {line}", flush=True)
        if listener is not None:
            listener(line)
    stream.close()


def popen_stream(
    name: str,
    command: str,
    args: list[str],
    cwd: Path,
    env: dict[str, str] | None = None,
    listener=None,
) -> subprocess.Popen:
    log(f"starting {name}: {format_command(command, args)}")
    prepared_command, prepared_args = prepare_command(command, args)
    creation_flags = 0
    if WINDOWS:
        creation_flags = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    try:
        child = subprocess.Popen(
            [prepared_command, *prepared_args],
            cwd=str(cwd),
            env=env,
            stdin=None,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
            start_new_session=not WINDOWS,
            creationflags=creation_flags,
        )
    except OSError as error:
        child_failures.append(f"{name} could not start: {error}")
        raise LauncherError(f"{name} could not start: {error}") from error
    processes.append(child)
    process_names[id(child)] = name
    for stream, is_stdout in ((child.stdout, True), (child.stderr, False)):
        thread = threading.Thread(
            target=pump_output,
            args=(name, stream, listener if is_stdout else None),
            daemon=True,
        )
        thread.start()
    return child


def process_exists(pid: int) -> bool:
    if pid <= 0:
        return False
    if WINDOWS:
        result = subprocess.run(
            ["tasklist.exe", "/FI", f"PID eq {pid}"],
            capture_output=True,
            text=True,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        return re.search(rf"\b{pid}\b", result.stdout or "") is not None
    try:
        os.kill(pid, 0)
        return True
    except PermissionError:
        return True
    except OSError:
        return False


def command_output(command: str, args: list[str]) -> str:
    try:
        result = subprocess.run(
            [command, *args],
            capture_output=True,
            text=True,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except OSError:
        return ""
    return result.stdout or ""


def find_listening_pids(port: int) -> set[int]:
    pids: set[int] = set()
    if WINDOWS:
        for line in command_output("netstat.exe", ["-ano", "-p", "tcp"]).splitlines():
            parts = line.split()
            if len(parts) < 5 or parts[0].upper() != "TCP" or parts[3].upper() != "LISTENING":
                continue
            separator = parts[1].rfind(":")
            if separator != -1 and parts[1][separator + 1 :] == str(port):
                pid = int(parts[-1])
                pids.add(pid)
        return pids
    if command_exists("lsof"):
        for raw_pid in command_output("lsof", ["-nP", f"-tiTCP:{port}", "-sTCP:LISTEN"]).splitlines():
            try:
                pid = int(raw_pid.strip())
            except ValueError:
                continue
            if pid > 0:
                pids.add(pid)
        return pids
    if command_exists("fuser"):
        for raw_pid in command_output("fuser", [f"{port}/tcp"]).strip().split():
            try:
                pid = int(raw_pid)
            except ValueError:
                continue
            if pid > 0:
                pids.add(pid)
    return pids


def stop_pid(pid: int, force: bool, tree: bool) -> None:
    if WINDOWS:
        args = [*(["/F"] if force else []), *(["/T"] if tree else []), "/PID", str(pid)]
        subprocess.run(
            ["taskkill.exe", *args],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        return
    try:
        if tree:
            os.killpg(os.getpgid(pid), signal.SIGKILL if force else signal.SIGTERM)
        else:
            os.kill(pid, signal.SIGKILL if force else signal.SIGTERM)
    except ProcessLookupError:
        return
    except OSError:
        return


def kill_processes_on_port(service: str, port: int) -> bool:
    pids = sorted(pid for pid in find_listening_pids(port) if pid != os.getpid())
    if not pids:
        return False
    log(f"{service} is using port {port}; stopping PID(s): {', '.join(str(pid) for pid in pids)}")
    for pid in pids:
        stop_pid(pid, False, WINDOWS)
    deadline = time.monotonic() + 5
    while time.monotonic() < deadline:
        if not any(process_exists(pid) for pid in pids):
            return True
        time.sleep(0.2)
    remaining = [pid for pid in pids if process_exists(pid)]
    if remaining:
        log(f"force stopping PID(s): {', '.join(str(pid) for pid in remaining)}")
    for pid in remaining:
        stop_pid(pid, True, WINDOWS)
    return True


def stop_children() -> None:
    global stopping
    if stopping:
        return
    stopping = True
    running_pids = [child.pid for child in processes if child.pid and process_exists(child.pid)]
    for pid in running_pids:
        stop_pid(pid, WINDOWS, True)
    deadline = time.monotonic() + 8
    while time.monotonic() < deadline and any(process_exists(pid) for pid in running_pids):
        time.sleep(0.1)
    for pid in [pid for pid in running_pids if process_exists(pid)]:
        stop_pid(pid, True, True)
    for port in sorted(managed_ports):
        kill_processes_on_port(f"port {port}", port)


def check_children() -> None:
    if shutdown_requested:
        return
    if child_failures:
        fail(child_failures.pop(0))
    for child in processes:
        status = child.poll()
        if status is None:
            continue
        name = process_names.get(id(child), "child process")
        fail(f"{name} exited unexpectedly with exit code {status}")


def parse_database_host_port(env: dict[str, str]) -> tuple[str, int]:
    database_url = get_env(env, "DATABASE_URL") or "jdbc:postgresql://localhost:5434/laborflow"
    if database_url.startswith("jdbc:"):
        database_url = database_url[5:]
    try:
        parsed = urlparse(database_url)
        port = int(parsed.port) if parsed.port else 5434
    except ValueError:
        fail(f"DATABASE_URL is invalid: {database_url}")
    if port < 1 or port > 65535:
        fail(f"DATABASE_URL contains an invalid TCP port: {database_url}")
    return parsed.hostname or "localhost", port


def parse_port(env: dict[str, str], name: str, default_value: int) -> int:
    raw = get_env(env, name) or str(default_value)
    if not re.fullmatch(r"[+-]?\d+", raw):
        fail(f"{name} must be a valid TCP port, got: {raw}")
    port = int(raw)
    if port < 1 or port > 65535:
        fail(f"{name} must be between 1 and 65535, got: {raw}")
    return port


def can_connect(host: str, port: int, timeout_seconds: float) -> bool:
    try:
        with socket.create_connection((host, port), timeout=timeout_seconds):
            return True
    except OSError:
        return False


def ensure_port_available(service: str, host: str, port: int, env_name: str) -> None:
    if not find_listening_pids(port) and not can_connect(host, port, 1.0):
        return
    kill_processes_on_port(service, port)
    if find_listening_pids(port) or can_connect(host, port, 1.0):
        fail(
            f"{service} port {port} is still in use after cleanup. "
            f"Stop the existing process or set {env_name} to another port."
        )


def wait_for_port(service: str, host: str, port: int, timeout_seconds: int = 60) -> None:
    log(f"waiting for {service} at {host}:{port}")
    deadline = time.monotonic() + timeout_seconds
    while time.monotonic() < deadline and not shutdown_requested:
        check_failure()
        check_children()
        if can_connect(host, port, 2.0):
            log(f"{service} is reachable")
            return
        time.sleep(1)
    if not shutdown_requested:
        check_failure()
        fail(f"{service} is not reachable at {host}:{port}")


def ensure_docker(env: dict[str, str]) -> None:
    if not command_exists("docker"):
        fail("docker is required unless --no-docker is used")
    if not (COMPOSE_DIR / "docker-compose.yml").exists():
        fail(f"docker-compose.yml not found in {COMPOSE_DIR}")
    run_checked("docker", ["compose", "up", "-d"], COMPOSE_DIR, env)


def stop_docker(env: dict[str, str]) -> None:
    if not command_exists("docker"):
        fail("docker command not found")
    if not (COMPOSE_DIR / "docker-compose.yml").exists():
        fail(f"docker-compose.yml not found in {COMPOSE_DIR}")
    run_checked("docker", ["compose", "down"], COMPOSE_DIR, env)


def find_java_home(env: dict[str, str]) -> str:
    configured = get_env(env, "JAVA_HOME")
    if configured:
        executable = Path(configured) / "bin" / ("java.exe" if WINDOWS else "java")
        if executable.exists():
            return configured
    java = find_command("java")
    if java is not None:
        return str(Path(java).resolve().parent.parent)
    fail("Java not found. Set JAVA_HOME or install JDK 21 on PATH.")


def find_maven(env: dict[str, str]) -> str:
    configured = get_env(env, "MAVEN_BIN")
    if configured and Path(configured).exists():
        return configured
    maven = find_command("mvn")
    if maven is not None:
        return maven
    fail("Maven not found. Set MAVEN_BIN or install Maven on PATH.")


def find_pnpm(env: dict[str, str]) -> str:
    configured = get_env(env, "PNPM_BIN")
    if configured and Path(configured).exists():
        return configured
    pnpm = find_command("pnpm")
    if pnpm is not None:
        return pnpm
    fail("pnpm not found. Set PNPM_BIN or install pnpm on PATH.")


def find_node(env: dict[str, str]) -> str:
    configured = get_env(env, "NODE_BIN")
    if configured and Path(configured).exists():
        return configured
    node = find_command("node")
    if node is not None:
        return node
    fail("Node.js not found. Set NODE_BIN or install Node.js on PATH.")


def ensure_desktop_dependencies(env: dict[str, str]) -> None:
    run_checked(find_pnpm(env), ["install", "--frozen-lockfile"], DESKTOP_DIR, env)


def desktop_environment(env: dict[str, str]) -> dict[str, str]:
    desktop_env = dict(env)
    for name in [
        "ELECTRON_INSTALL_ARCH",
        "ELECTRON_INSTALL_PLATFORM",
        "ELECTRON_OVERRIDE_DIST_PATH",
        "ELECTRON_RUN_AS_NODE",
        "npm_config_arch",
        "npm_config_platform",
    ]:
        unset_env(desktop_env, name)
    if get_env(desktop_env, "VITE_API_BASE_URL") is None:
        set_env(
            desktop_env,
            "VITE_API_BASE_URL",
            f"http://localhost:{get_env(env, 'SERVER_PORT') or '8089'}/api",
        )
    return desktop_env


def electron_runtime_path() -> Path:
    dist = DESKTOP_DIR / "node_modules" / "electron" / "dist"
    if node_platform() == "darwin":
        return dist / "Electron.app" / "Contents" / "MacOS" / "Electron"
    return dist / ("electron.exe" if WINDOWS else "electron")


def ensure_electron_runtime(env: dict[str, str]) -> None:
    electron_package = DESKTOP_DIR / "node_modules" / "electron"
    install_script = electron_package / "install.js"
    if not install_script.exists():
        fail(
            "Electron dependency is missing. "
            "Run again without --skip-install to install desktop dependencies."
        )
    runtime_env = desktop_environment(env)
    set_env(runtime_env, "ELECTRON_INSTALL_PLATFORM", node_platform())
    set_env(runtime_env, "ELECTRON_INSTALL_ARCH", node_arch())
    runtime = electron_runtime_path()
    if not executable_exists(str(runtime)):
        log(
            f"Electron runtime for {node_platform()}/{node_arch()} is missing; "
            "downloading it before services start"
        )
        run_checked(find_node(env), [str(install_script)], DESKTOP_DIR, runtime_env)
    if not executable_exists(str(runtime)):
        fail(f"Electron runtime was not installed at {runtime}")
    try:
        result = subprocess.run(
            [str(runtime), "--version"],
            cwd=str(DESKTOP_DIR),
            env=runtime_env,
            capture_output=True,
            text=True,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except OSError as error:
        fail(f"Electron runtime could not execute: {error}")
    if result.returncode != 0:
        reason = (result.stderr or "").strip() or "unknown error"
        fail(f"Electron runtime could not execute: {reason}")
    log(
        f"Electron {(result.stdout or '').strip() or 'runtime'} is ready for "
        f"{node_platform()}/{node_arch()}"
    )


def ensure_miniapp_dependencies(env: dict[str, str]) -> None:
    if not MINIAPP_DIR.exists():
        return
    run_checked(find_pnpm(env), ["install", "--frozen-lockfile"], MINIAPP_DIR, env)


def start_server(env: dict[str, str]) -> subprocess.Popen:
    java_home = find_java_home(env)
    maven = find_maven(env)
    server_env = dict(env)
    set_env(server_env, "JAVA_HOME", java_home)
    set_env(
        server_env,
        "PATH",
        f"{Path(java_home) / 'bin'}{os.pathsep}{get_env(server_env, 'PATH') or ''}",
    )
    if get_env(server_env, "TZ") is None:
        set_env(server_env, "TZ", "Asia/Shanghai")
    return popen_stream(
        "server",
        maven,
        ["spring-boot:run"],
        SERVER_DIR,
        server_env,
    )


def start_desktop(env: dict[str, str]):
    window_ready = False

    def on_line(line: str) -> None:
        nonlocal window_ready
        if "LaborFlow desktop window is ready" in line:
            window_ready = True

    popen_stream(
        "desktop",
        find_pnpm(env),
        ["run", "dev"],
        DESKTOP_DIR,
        desktop_environment(env),
        on_line,
    )
    return lambda: window_ready


def start_miniapp(env: dict[str, str]) -> subprocess.Popen:
    return popen_stream(
        "miniapp",
        find_pnpm(env),
        ["run", "dev"],
        MINIAPP_DIR,
        env,
    )


def wait_for_desktop_window(is_ready, timeout_seconds: int = 60) -> None:
    log("waiting for the Electron desktop window")
    deadline = time.monotonic() + timeout_seconds
    while time.monotonic() < deadline and not shutdown_requested:
        check_failure()
        check_children()
        if is_ready():
            log("Electron desktop window is visible")
            return
        time.sleep(0.5)
    if not shutdown_requested:
        check_failure()
        fail(
            "Electron started its renderer but did not show a window. "
            "Check the [desktop] output above for the main-process error."
        )


def wait_forever(miniapp_enabled: bool) -> None:
    env = merged_env()
    server_port = get_env(env, "SERVER_PORT") or "8089"
    log(
        f"started. Desktop renderer: http://localhost:5175  "
        f"API: http://localhost:{server_port}"
    )
    if miniapp_enabled:
        log("miniapp watch build output: clients/miniapp/dist/ (open it in WeChat DevTools)")
    log("press Ctrl+C to stop server, desktop, and miniapp processes")
    while not shutdown_requested:
        check_failure()
        check_children()
        time.sleep(1)


def print_help() -> None:
    print(
        """Usage: python3 run.py [options]

Start LaborFlow local development services.

Options:
  --no-docker    skip docker compose startup
  --no-miniapp   skip the Taro miniapp watch build
  --skip-install skip pnpm install
  --stop         stop docker compose services and exit
  -h, --help     display this help"""
    )


def parse_arguments(argv: list[str]) -> dict[str, bool] | None:
    result = {"no_docker": False, "no_miniapp": False, "skip_install": False, "stop": False}
    for argument in argv:
        if argument in ("-h", "--help"):
            print_help()
            return None
        if argument == "--no-docker":
            result["no_docker"] = True
        elif argument == "--no-miniapp":
            result["no_miniapp"] = True
        elif argument == "--skip-install":
            result["skip_install"] = True
        elif argument == "--stop":
            result["stop"] = True
        else:
            fail(f"unknown argument: {argument}")
    return result


def main() -> None:
    args = parse_arguments(sys.argv[1:])
    if args is None:
        return
    ensure_env_file()
    env = merged_env()
    if args["stop"]:
        stop_docker(env)
        return
    if not args["no_docker"]:
        ensure_docker(env)
    host, database_port = parse_database_host_port(env)
    wait_for_port("PostgreSQL", host, database_port)
    server_port = parse_port(env, "SERVER_PORT", 8089)
    desktop_port = 5175
    managed_ports.add(server_port)
    managed_ports.add(desktop_port)
    ensure_port_available("API", "localhost", server_port, "SERVER_PORT")
    ensure_port_available(
        "Desktop renderer",
        "localhost",
        desktop_port,
        "desktop Vite port",
    )
    if not args["skip_install"]:
        ensure_desktop_dependencies(env)
        if not args["no_miniapp"]:
            ensure_miniapp_dependencies(env)
    ensure_electron_runtime(env)
    start_server(env)
    desktop_window_ready = start_desktop(env)
    if not args["no_miniapp"]:
        start_miniapp(env)

    waiters = [
        threading.Thread(
            target=run_waiter,
            args=(wait_for_port, "API", "localhost", server_port),
            daemon=True,
        ),
        threading.Thread(
            target=run_waiter,
            args=(wait_for_port, "Desktop renderer", "localhost", desktop_port),
            daemon=True,
        ),
        threading.Thread(
            target=run_waiter,
            args=(wait_for_desktop_window, desktop_window_ready),
            daemon=True,
        ),
    ]
    for waiter in waiters:
        waiter.start()
    for waiter in waiters:
        waiter.join()
    check_failure()
    wait_forever(not args["no_miniapp"])


def handle_signal(signum, frame) -> None:
    global shutdown_requested
    if shutdown_requested:
        return
    shutdown_requested = True
    log("stopping...")
    stop_children()
    sys.exit(0)


for signal_name in ("SIGINT", "SIGTERM"):
    if hasattr(signal, signal_name):
        signal.signal(getattr(signal, signal_name), handle_signal)

try:
    main()
except LauncherError as error:
    print(f"[run] ERROR: {error}", file=sys.stderr, flush=True)
    sys.exit(1)
finally:
    stop_children()
