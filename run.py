#!/usr/bin/env python3
"""
LaborFlow local launcher.

Usage:
  python3 run.py              # start PostgreSQL, server, desktop, and miniapp watch
  python3 run.py --no-docker  # skip docker compose
  python3 run.py --no-miniapp # skip the Taro miniapp watch build
  python3 run.py --skip-install
  python3 run.py --stop       # stop docker compose services
"""

from __future__ import annotations

import argparse
import os
import secrets
import shutil
import signal
import socket
import subprocess
import sys
import threading
import time
from pathlib import Path
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parent
DESKTOP_DIR = ROOT / "clients" / "desktop"
MINIAPP_DIR = ROOT / "clients" / "miniapp"
SERVER_DIR = ROOT / "server"
ENV_FILE = ROOT / ".env"
ENV_EXAMPLE = ROOT / ".env.example"
COMPOSE_DIR = ROOT / "deploy" / "docker-laborflow"

processes: list[subprocess.Popen[str]] = []
managed_ports: set[int] = set()
stopping = False


def log(message: str) -> None:
    print(f"[run] {message}", flush=True)


def fail(message: str) -> None:
    print(f"[run] ERROR: {message}", file=sys.stderr, flush=True)
    stop_children()
    sys.exit(1)


def read_env_file(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def merged_env() -> dict[str, str]:
    env = os.environ.copy()
    env.update(read_env_file(ENV_FILE))
    return env


def _random_password() -> str:
    """A machine-local random dev secret (never committed)."""
    return secrets.token_urlsafe(18)


def _write_generated_env(path: Path) -> None:
    """Write a fresh .env with strong random dev credentials.

    Never uses the committed placeholder values (laborflow123 etc.) so that a
    fresh clone does not start with a known database password.
    """
    postgres_password = _random_password()
    jwt_secret = secrets.token_urlsafe(48)
    path.write_text(
        "\n".join(
            [
                "SPRING_PROFILES_ACTIVE=dev",
                "POSTGRES_DB=laborflow",
                "POSTGRES_USER=laborflow",
                f"POSTGRES_PASSWORD={postgres_password}",
                "DATABASE_URL=jdbc:postgresql://localhost:5434/laborflow",
                "SERVER_PORT=8089",
                f"# Dev-only random secret generated by run.py. Replace before staging/production.\nJWT_SECRET={jwt_secret}",
                "BOOTSTRAP_ADMIN_USERNAME=",
                "BOOTSTRAP_ADMIN_PASSWORD=",
                "UPLOAD_DIR=./uploads",
                "FILE_STORAGE_TYPE=local",
                "",
            ]
        ),
        encoding="utf-8",
    )


def ensure_env_file() -> None:
    if ENV_FILE.exists():
        return
    if ENV_EXAMPLE.exists():
        # Copy the example as a template, but replace the known weak/placeholder
        # values with freshly generated random dev secrets so no fresh clone ever
        # runs with the committed defaults.
        lines = ENV_EXAMPLE.read_text(encoding="utf-8").splitlines()
        replacements = {
            "POSTGRES_PASSWORD": _random_password(),
            "JWT_SECRET": secrets.token_urlsafe(48),
        }
        patched: list[str] = []
        for raw_line in lines:
            line = raw_line
            if "=" in line and not line.lstrip().startswith("#"):
                key = line.split("=", 1)[0].strip()
                if key in replacements:
                    line = f"{key}={replacements[key]}"
            patched.append(line)
        ENV_FILE.write_text("\n".join(patched) + "\n", encoding="utf-8")
        log("created .env from .env.example with random dev secrets")
    else:
        _write_generated_env(ENV_FILE)
        log("created default .env with random dev secrets")


def command_exists(command: str) -> bool:
    return shutil.which(command) is not None


def prepare_cmd(cmd: list[str]) -> list[str]:
    # On Windows, npm/Maven CLIs ship as .cmd shims (pnpm.CMD, mvn.CMD).
    # CreateProcess cannot launch .cmd/.bat directly — only real .exe files —
    # so route through cmd.exe to avoid a spurious "command not found".
    if os.name == "nt":
        return ["cmd", "/c", *cmd]
    return cmd


def run_checked(cmd: list[str], cwd: Path, env: dict[str, str] | None = None) -> None:
    log(f"running: {' '.join(cmd)}")
    try:
        subprocess.run(prepare_cmd(cmd), cwd=cwd, env=env, check=True)
    except FileNotFoundError:
        fail(f"command not found: {cmd[0]}")
    except subprocess.CalledProcessError as exc:
        fail(f"command failed with exit code {exc.returncode}: {' '.join(cmd)}")


def popen_stream(name: str, cmd: list[str], cwd: Path, env: dict[str, str] | None = None) -> subprocess.Popen[str]:
    log(f"starting {name}: {' '.join(cmd)}")
    popen_kwargs: dict[str, object] = {}
    if os.name == "nt":
        popen_kwargs["creationflags"] = subprocess.CREATE_NEW_PROCESS_GROUP
    else:
        popen_kwargs["start_new_session"] = True
    try:
        proc = subprocess.Popen(
            prepare_cmd(cmd),
            cwd=cwd,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            # Force UTF-8: child output (e.g. Vite's ➜) is UTF-8, but Windows text
            # mode defaults to the locale codepage (GBK/cp936) and crashes the pump.
            encoding="utf-8",
            errors="replace",
            bufsize=1,
            **popen_kwargs,
        )
    except FileNotFoundError:
        fail(f"command not found: {cmd[0]}")

    processes.append(proc)

    def pump() -> None:
        assert proc.stdout is not None
        for line in proc.stdout:
            print(f"[{name}] {line}", end="", flush=True)

    threading.Thread(target=pump, daemon=True).start()
    return proc


def stop_children() -> None:
    global stopping
    if stopping:
        return
    stopping = True
    for proc in processes:
        if proc.poll() is None:
            if os.name == "nt":
                # Commands run via cmd.exe (see prepare_cmd); terminating the wrapper
                # would not reach its grandchildren (java/node), so kill the whole tree.
                subprocess.run(
                    ["taskkill", "/F", "/T", "/PID", str(proc.pid)],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
            else:
                try:
                    os.killpg(proc.pid, signal.SIGTERM)
                except ProcessLookupError:
                    pass
    deadline = time.time() + 8
    for proc in processes:
        if proc.poll() is None:
            remaining = max(0.1, deadline - time.time())
            try:
                proc.wait(timeout=remaining)
            except subprocess.TimeoutExpired:
                if os.name == "nt":
                    subprocess.run(
                        ["taskkill", "/F", "/T", "/PID", str(proc.pid)],
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL,
                    )
                else:
                    try:
                        os.killpg(proc.pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
                try:
                    proc.wait(timeout=1)
                except subprocess.TimeoutExpired:
                    pass
    for port in sorted(managed_ports):
        kill_processes_on_port(f"port {port}", port)


def process_exists(pid: int) -> bool:
    if pid <= 0:
        return False
    if os.name == "nt":
        result = subprocess.run(
            ["tasklist", "/FI", f"PID eq {pid}"],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
        )
        return str(pid) in result.stdout
    try:
        os.kill(pid, 0)
        return True
    except ProcessLookupError:
        return False
    except PermissionError:
        return True


def find_listening_pids(port: int) -> set[int]:
    pids: set[int] = set()
    if os.name == "nt":
        result = subprocess.run(
            ["netstat", "-ano", "-p", "tcp"],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
        )
        for line in result.stdout.splitlines():
            parts = line.split()
            if len(parts) < 5 or parts[0].upper() != "TCP" or parts[3].upper() != "LISTENING":
                continue
            local_address = parts[1].rsplit(":", 1)
            if len(local_address) == 2 and local_address[1] == str(port):
                try:
                    pids.add(int(parts[-1]))
                except ValueError:
                    pass
        return pids

    if command_exists("lsof"):
        result = subprocess.run(
            ["lsof", "-nP", f"-tiTCP:{port}", "-sTCP:LISTEN"],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
        )
        for raw_pid in result.stdout.splitlines():
            try:
                pids.add(int(raw_pid.strip()))
            except ValueError:
                pass
        return pids

    if command_exists("fuser"):
        result = subprocess.run(
            ["fuser", f"{port}/tcp"],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
        )
        for raw_pid in result.stdout.split():
            try:
                pids.add(int(raw_pid.strip()))
            except ValueError:
                pass
    return pids


def kill_processes_on_port(service: str, port: int) -> bool:
    pids = {pid for pid in find_listening_pids(port) if pid != os.getpid()}
    if not pids:
        return False

    log(f"{service} is using port {port}; stopping PID(s): {', '.join(map(str, sorted(pids)))}")
    for pid in sorted(pids):
        if os.name == "nt":
            subprocess.run(
                ["taskkill", "/T", "/PID", str(pid)],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                check=False,
            )
        else:
            try:
                os.kill(pid, signal.SIGTERM)
            except ProcessLookupError:
                pass

    deadline = time.time() + 5
    while time.time() < deadline:
        if not any(process_exists(pid) for pid in pids):
            return True
        time.sleep(0.2)

    remaining = [pid for pid in sorted(pids) if process_exists(pid)]
    if remaining:
        log(f"force stopping PID(s): {', '.join(map(str, remaining))}")
    for pid in remaining:
        if os.name == "nt":
            subprocess.run(
                ["taskkill", "/F", "/T", "/PID", str(pid)],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                check=False,
            )
        else:
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
    return True


def parse_database_host_port(env: dict[str, str]) -> tuple[str, int]:
    url = env.get("DATABASE_URL", "jdbc:postgresql://localhost:5434/laborflow")
    if url.startswith("jdbc:"):
        url = url[5:]
    parsed = urlparse(url)
    return parsed.hostname or "localhost", parsed.port or 5434


def parse_port(env: dict[str, str], name: str, default: int) -> int:
    raw = env.get(name, str(default))
    try:
        port = int(raw)
    except ValueError:
        fail(f"{name} must be a valid TCP port, got: {raw}")
    if port < 1 or port > 65535:
        fail(f"{name} must be between 1 and 65535, got: {raw}")
    return port


def ensure_port_available(service: str, host: str, port: int, env_name: str) -> None:
    try:
        with socket.create_connection((host, port), timeout=1):
            pass
    except OSError:
        return

    kill_processes_on_port(service, port)
    try:
        with socket.create_connection((host, port), timeout=1):
            fail(
                f"{service} port {port} is still in use after cleanup. "
                f"Stop the existing process or set {env_name} to another port."
            )
    except OSError:
        return

def wait_for_port(service: str, host: str, port: int, timeout_seconds: int = 60) -> None:
    log(f"waiting for {service} at {host}:{port}")
    deadline = time.time() + timeout_seconds
    while time.time() < deadline:
        for proc in processes:
            code = proc.poll()
            if code is not None:
                fail(f"a child process exited unexpectedly with code {code}")
        try:
            with socket.create_connection((host, port), timeout=2):
                log(f"{service} is reachable")
                return
        except OSError:
            pass
        time.sleep(1)
    fail(f"{service} is not reachable at {host}:{port}")


def ensure_docker(env: dict[str, str]) -> None:
    if not command_exists("docker"):
        fail("docker is required unless --no-docker is used")
    if not (COMPOSE_DIR / "docker-compose.yml").exists():
        fail(f"docker-compose.yml not found in {COMPOSE_DIR}")
    run_checked(["docker", "compose", "up", "-d"], COMPOSE_DIR, env)


def stop_docker(env: dict[str, str]) -> None:
    if not command_exists("docker"):
        fail("docker command not found")
    if not (COMPOSE_DIR / "docker-compose.yml").exists():
        fail(f"docker-compose.yml not found in {COMPOSE_DIR}")
    run_checked(["docker", "compose", "down"], COMPOSE_DIR, env)


def find_java_home(env: dict[str, str]) -> Path:
    # Priority: $JAVA_HOME -> `java` on PATH. No machine-specific fallback —
    # the launcher must be portable across developer machines and CI runners.
    configured = env.get("JAVA_HOME")
    if configured and (Path(configured) / "bin" / "java").exists():
        return Path(configured)
    java = shutil.which("java")
    if java:
        return Path(java).resolve().parents[1]
    fail("Java not found. Set JAVA_HOME or install JDK 21 on PATH.")
    raise AssertionError("unreachable")


def find_maven(env: dict[str, str]) -> str:
    # Priority: $MAVEN_BIN -> `mvn` on PATH.
    configured = env.get("MAVEN_BIN")
    if configured and Path(configured).exists():
        return configured
    mvn = shutil.which("mvn")
    if mvn:
        return mvn
    fail("Maven not found. Set MAVEN_BIN or install Maven on PATH.")
    raise AssertionError("unreachable")


def ensure_desktop_dependencies(env: dict[str, str]) -> None:
    if not command_exists("pnpm"):
        fail("pnpm is required for the desktop project")
    run_checked(["pnpm", "install"], DESKTOP_DIR, env)


def ensure_miniapp_dependencies(env: dict[str, str]) -> None:
    if not MINIAPP_DIR.exists():
        return
    if not command_exists("pnpm"):
        fail("pnpm is required for the miniapp project")
    run_checked(["pnpm", "install"], MINIAPP_DIR, env)


def start_server(env: dict[str, str]) -> subprocess.Popen[str]:
    java_home = find_java_home(env)
    maven = find_maven(env)
    server_env = env.copy()
    server_env["JAVA_HOME"] = str(java_home)
    server_env["PATH"] = f"{java_home / 'bin'}{os.pathsep}{server_env.get('PATH', '')}"
    # Pin the JVM default timezone so LocalDateTime-based audit fields and
    # business date math are deterministic regardless of the host locale.
    # Mirrors spring.jackson.time-zone in application.yml. See docs/TIMEZONE_POLICY.md.
    server_env.setdefault("TZ", "Asia/Shanghai")
    return popen_stream(
        "server",
        [maven, "spring-boot:run"],
        SERVER_DIR,
        server_env,
    )


def start_desktop(env: dict[str, str]) -> subprocess.Popen[str]:
    desktop_env = env.copy()
    desktop_env.setdefault("VITE_API_BASE_URL", f"http://localhost:{env.get('SERVER_PORT', '8089')}/api")
    return popen_stream("desktop", ["pnpm", "dev"], DESKTOP_DIR, desktop_env)


def start_miniapp(env: dict[str, str]) -> subprocess.Popen[str]:
    return popen_stream("miniapp", ["pnpm", "dev"], MINIAPP_DIR, env)


def wait_forever(miniapp_enabled: bool) -> None:
    env = merged_env()
    server_port = env.get("SERVER_PORT", "8089")
    log(f"started. Desktop renderer: http://localhost:5175  API: http://localhost:{server_port}")
    if miniapp_enabled:
        log("miniapp watch build output: clients/miniapp/dist/ (open it in WeChat DevTools)")
    log("press Ctrl+C to stop server, desktop, and miniapp processes")
    while True:
        for proc in processes:
            code = proc.poll()
            if code is not None:
                fail(f"a child process exited unexpectedly with code {code}")
        time.sleep(1)


def main() -> None:
    parser = argparse.ArgumentParser(description="Start LaborFlow local development services.")
    parser.add_argument("--no-docker", action="store_true", help="skip docker compose startup")
    parser.add_argument("--no-miniapp", action="store_true", help="skip the Taro miniapp watch build")
    parser.add_argument("--skip-install", action="store_true", help="skip pnpm install")
    parser.add_argument("--stop", action="store_true", help="stop docker compose services and exit")
    args = parser.parse_args()

    ensure_env_file()
    env = merged_env()

    if args.stop:
        stop_docker(env)
        return

    if not args.no_docker:
        ensure_docker(env)

    host, port = parse_database_host_port(env)
    wait_for_port("PostgreSQL", host, port)

    server_port = parse_port(env, "SERVER_PORT", 8089)
    desktop_port = 5175
    managed_ports.update({server_port, desktop_port})
    ensure_port_available("API", "localhost", server_port, "SERVER_PORT")
    ensure_port_available("Desktop renderer", "localhost", desktop_port, "desktop Vite port")

    if not args.skip_install:
        ensure_desktop_dependencies(env)
        if not args.no_miniapp:
            ensure_miniapp_dependencies(env)

    start_server(env)
    start_desktop(env)
    if not args.no_miniapp:
        start_miniapp(env)
    wait_for_port("API", "localhost", server_port)
    wait_for_port("Desktop renderer", "localhost", desktop_port)
    wait_forever(not args.no_miniapp)


def shutdown(_sig: int, _frame: object) -> None:
    log("stopping...")
    stop_children()
    sys.exit(0)


if __name__ == "__main__":
    signal.signal(signal.SIGINT, shutdown)
    signal.signal(signal.SIGTERM, shutdown)
    try:
        main()
    finally:
        stop_children()
