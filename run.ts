#!/usr/bin/env bun

const fs = require("node:fs") as typeof import("node:fs");
const net = require("node:net") as typeof import("node:net");
const path = require("node:path") as typeof import("node:path");
const nodeCrypto = require("node:crypto") as typeof import("node:crypto");
const readline = require("node:readline") as typeof import("node:readline");
const { spawn, spawnSync } =
  require("node:child_process") as typeof import("node:child_process");

type Environment = Record<string, string>;
type ChildProcess = import("node:child_process").ChildProcess;
type Readable = import("node:stream").Readable;

interface Arguments {
  noDocker: boolean;
  noMiniapp: boolean;
  skipInstall: boolean;
  stop: boolean;
}

interface PreparedCommand {
  command: string;
  args: string[];
}

const ROOT = path.dirname(fs.realpathSync(__filename));
const DESKTOP_DIR = path.join(ROOT, "clients", "desktop");
const MINIAPP_DIR = path.join(ROOT, "clients", "miniapp");
const SERVER_DIR = path.join(ROOT, "server");
const ENV_FILE = path.join(ROOT, ".env");
const ENV_EXAMPLE = path.join(ROOT, ".env.example");
const COMPOSE_DIR = path.join(ROOT, "deploy", "docker-laborflow");

const processes: ChildProcess[] = [];
const childFailures: string[] = [];
const managedPorts = new Set<number>();
let stoppingPromise: Promise<void> | undefined;
let shutdownRequested = false;

class LauncherError extends Error {}

function log(message: string): void {
  console.log(`[run] ${message}`);
}

function fail(message: string): never {
  throw new LauncherError(message);
}

function readEnvFile(filePath: string): Environment {
  const values: Environment = {};
  if (!fs.existsSync(filePath)) {
    return values;
  }
  for (const rawLine of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) {
      continue;
    }
    const separator = line.indexOf("=");
    const key = line.slice(0, separator).trim();
    const value = line
      .slice(separator + 1)
      .trim()
      .replace(/^"+|"+$/g, "")
      .replace(/^'+|'+$/g, "");
    values[key] = value;
  }
  return values;
}

function mergedEnv(): Environment {
  const env: Environment = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value !== undefined) {
      env[key] = value;
    }
  }
  return { ...env, ...readEnvFile(ENV_FILE) };
}

function getEnv(env: Environment, name: string): string | undefined {
  if (env[name] !== undefined) {
    return env[name];
  }
  if (process.platform !== "win32") {
    return undefined;
  }
  const actualName = Object.keys(env).find(
    (key) => key.toLowerCase() === name.toLowerCase(),
  );
  return actualName === undefined ? undefined : env[actualName];
}

function setEnv(env: Environment, name: string, value: string): void {
  if (process.platform === "win32") {
    const actualName = Object.keys(env).find(
      (key) => key.toLowerCase() === name.toLowerCase(),
    );
    if (actualName !== undefined && actualName !== name) {
      delete env[actualName];
    }
  }
  env[name] = value;
}

function randomSecret(bytes: number): string {
  return nodeCrypto.randomBytes(bytes).toString("base64url");
}

function writeGeneratedEnv(filePath: string): void {
  const postgresPassword = randomSecret(18);
  const jwtSecret = randomSecret(48);
  fs.writeFileSync(
    filePath,
    [
      "SPRING_PROFILES_ACTIVE=dev",
      "POSTGRES_DB=laborflow",
      "POSTGRES_USER=laborflow",
      `POSTGRES_PASSWORD=${postgresPassword}`,
      "DATABASE_URL=jdbc:postgresql://localhost:5434/laborflow",
      "SERVER_PORT=8089",
      "# Dev-only random secret generated by run.ts. Replace before staging/production.",
      `JWT_SECRET=${jwtSecret}`,
      "BOOTSTRAP_ADMIN_USERNAME=",
      "BOOTSTRAP_ADMIN_PASSWORD=",
      "UPLOAD_DIR=./uploads",
      "FILE_STORAGE_TYPE=local",
      "",
    ].join("\n"),
    "utf8",
  );
}

function ensureEnvFile(): void {
  if (fs.existsSync(ENV_FILE)) {
    return;
  }
  if (!fs.existsSync(ENV_EXAMPLE)) {
    writeGeneratedEnv(ENV_FILE);
    log("created default .env with random dev secrets");
    return;
  }
  const replacements: Environment = {
    POSTGRES_PASSWORD: randomSecret(18),
    JWT_SECRET: randomSecret(48),
  };
  const patched = fs
    .readFileSync(ENV_EXAMPLE, "utf8")
    .split(/\r?\n/)
    .map((rawLine) => {
      if (!rawLine.includes("=") || rawLine.trimStart().startsWith("#")) {
        return rawLine;
      }
      const key = rawLine.slice(0, rawLine.indexOf("=")).trim();
      return replacements[key] === undefined
        ? rawLine
        : `${key}=${replacements[key]}`;
    });
  while (patched.length > 0 && patched.at(-1) === "") {
    patched.pop();
  }
  fs.writeFileSync(ENV_FILE, `${patched.join("\n")}\n`, "utf8");
  log("created .env from .env.example with random dev secrets");
}

function executableExists(filePath: string): boolean {
  try {
    fs.accessSync(
      filePath,
      process.platform === "win32" ? fs.constants.F_OK : fs.constants.X_OK,
    );
    return fs.statSync(filePath).isFile();
  } catch {
    return false;
  }
}

function findCommand(command: string): string | undefined {
  const hasPath =
    path.isAbsolute(command) || command.includes("/") || command.includes("\\");
  const pathValue =
    getEnv(
      Object.fromEntries(
        Object.entries(process.env).filter(
          (entry): entry is [string, string] => entry[1] !== undefined,
        ),
      ),
      "PATH",
    ) ?? "";
  const directories = hasPath ? [""] : pathValue.split(path.delimiter);
  const configuredExtensions =
    process.platform === "win32"
      ? (process.env.PATHEXT ?? ".COM;.EXE;.BAT;.CMD").split(";")
      : [""];
  const extensions =
    process.platform === "win32" && path.extname(command)
      ? ["", ...configuredExtensions]
      : configuredExtensions;
  for (const directory of directories) {
    for (const extension of extensions) {
      const candidate = hasPath
        ? `${command}${extension}`
        : path.join(directory, `${command}${extension}`);
      if (executableExists(candidate)) {
        return candidate;
      }
    }
  }
  return undefined;
}

function commandExists(command: string): boolean {
  return findCommand(command) !== undefined;
}

function prepareCommand(command: string, args: string[]): PreparedCommand {
  if (process.platform === "win32") {
    return { command: "cmd.exe", args: ["/d", "/s", "/c", command, ...args] };
  }
  return { command, args };
}

function formatCommand(command: string, args: string[]): string {
  return [command, ...args].join(" ");
}

function runChecked(
  command: string,
  args: string[],
  cwd: string,
  env?: Environment,
): void {
  log(`running: ${formatCommand(command, args)}`);
  const prepared = prepareCommand(command, args);
  const result = spawnSync(prepared.command, prepared.args, {
    cwd,
    env,
    stdio: "inherit",
    windowsHide: true,
  });
  if (result.error) {
    const error = result.error as NodeJS.ErrnoException;
    if (error.code === "ENOENT") {
      fail(`command not found: ${command}`);
    }
    fail(`could not run ${command}: ${error.message}`);
  }
  if (result.status !== 0) {
    fail(
      `command failed with exit code ${result.status ?? "unknown"}: ${formatCommand(command, args)}`,
    );
  }
}

function pumpOutput(name: string, stream: Readable | null): void {
  if (stream === null) {
    return;
  }
  stream.setEncoding("utf8");
  const lines = readline.createInterface({
    input: stream,
    crlfDelay: Infinity,
  });
  lines.on("line", (line) => console.log(`[${name}] ${line}`));
}

function popenStream(
  name: string,
  command: string,
  args: string[],
  cwd: string,
  env?: Environment,
): ChildProcess {
  log(`starting ${name}: ${formatCommand(command, args)}`);
  const prepared = prepareCommand(command, args);
  const child = spawn(prepared.command, prepared.args, {
    cwd,
    env,
    detached: process.platform !== "win32",
    stdio: ["inherit", "pipe", "pipe"],
    windowsHide: true,
  });
  processes.push(child);
  child.once("error", (error) =>
    childFailures.push(`${name} could not start: ${error.message}`),
  );
  pumpOutput(name, child.stdout);
  pumpOutput(name, child.stderr);
  return child;
}

function processExists(pid: number): boolean {
  if (pid <= 0) {
    return false;
  }
  if (process.platform === "win32") {
    const result = spawnSync("tasklist.exe", ["/FI", `PID eq ${pid}`], {
      encoding: "utf8",
      windowsHide: true,
    });
    return (result.stdout ?? "")
      .split(/\r?\n/)
      .some((line) => new RegExp(`\\b${pid}\\b`).test(line));
  }
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return (error as NodeJS.ErrnoException).code === "EPERM";
  }
}

function commandOutput(command: string, args: string[]): string {
  const result = spawnSync(command, args, {
    encoding: "utf8",
    windowsHide: true,
  });
  return typeof result.stdout === "string" ? result.stdout : "";
}

function findListeningPids(port: number): Set<number> {
  const pids = new Set<number>();
  if (process.platform === "win32") {
    for (const line of commandOutput("netstat.exe", [
      "-ano",
      "-p",
      "tcp",
    ]).split(/\r?\n/)) {
      const parts = line.trim().split(/\s+/);
      if (
        parts.length < 5 ||
        parts[0].toUpperCase() !== "TCP" ||
        parts[3].toUpperCase() !== "LISTENING"
      ) {
        continue;
      }
      const separator = parts[1].lastIndexOf(":");
      if (separator !== -1 && parts[1].slice(separator + 1) === String(port)) {
        const pid = Number(parts.at(-1));
        if (Number.isInteger(pid)) {
          pids.add(pid);
        }
      }
    }
    return pids;
  }
  if (commandExists("lsof")) {
    for (const rawPid of commandOutput("lsof", [
      "-nP",
      `-tiTCP:${port}`,
      "-sTCP:LISTEN",
    ]).split(/\r?\n/)) {
      const pid = Number(rawPid.trim());
      if (Number.isInteger(pid) && pid > 0) {
        pids.add(pid);
      }
    }
    return pids;
  }
  if (commandExists("fuser")) {
    for (const rawPid of commandOutput("fuser", [`${port}/tcp`])
      .trim()
      .split(/\s+/)) {
      const pid = Number(rawPid);
      if (Number.isInteger(pid) && pid > 0) {
        pids.add(pid);
      }
    }
  }
  return pids;
}

function stopPid(pid: number, force: boolean, tree: boolean): void {
  if (process.platform === "win32") {
    const args = [
      ...(force ? ["/F"] : []),
      ...(tree ? ["/T"] : []),
      "/PID",
      String(pid),
    ];
    spawnSync("taskkill.exe", args, { stdio: "ignore", windowsHide: true });
    return;
  }
  try {
    process.kill(tree ? -pid : pid, force ? "SIGKILL" : "SIGTERM");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ESRCH") {
      throw error;
    }
  }
}

function sleep(milliseconds: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

async function killProcessesOnPort(
  service: string,
  port: number,
): Promise<boolean> {
  const pids = [...findListeningPids(port)]
    .filter((pid) => pid !== process.pid)
    .sort((left, right) => left - right);
  if (pids.length === 0) {
    return false;
  }
  log(`${service} is using port ${port}; stopping PID(s): ${pids.join(", ")}`);
  for (const pid of pids) {
    stopPid(pid, false, process.platform === "win32");
  }
  const deadline = Date.now() + 5_000;
  while (Date.now() < deadline) {
    if (!pids.some(processExists)) {
      return true;
    }
    await sleep(200);
  }
  const remaining = pids.filter(processExists);
  if (remaining.length > 0) {
    log(`force stopping PID(s): ${remaining.join(", ")}`);
  }
  for (const pid of remaining) {
    stopPid(pid, true, process.platform === "win32");
  }
  return true;
}

function stopChildren(): Promise<void> {
  if (stoppingPromise !== undefined) {
    return stoppingPromise;
  }
  stoppingPromise = (async () => {
    const runningPids = processes
      .map((child) => child.pid)
      .filter((pid): pid is number => pid !== undefined && processExists(pid));
    for (const pid of runningPids) {
      stopPid(pid, process.platform === "win32", true);
    }
    const deadline = Date.now() + 8_000;
    while (Date.now() < deadline && runningPids.some(processExists)) {
      await sleep(100);
    }
    for (const pid of runningPids.filter(processExists)) {
      stopPid(pid, true, true);
    }
    for (const port of [...managedPorts].sort((left, right) => left - right)) {
      await killProcessesOnPort(`port ${port}`, port);
    }
  })();
  return stoppingPromise;
}

function checkChildren(): void {
  if (shutdownRequested) {
    return;
  }
  const failure = childFailures.shift();
  if (failure !== undefined) {
    fail(failure);
  }
  for (const child of processes) {
    if (child.exitCode !== null || child.signalCode !== null) {
      fail(
        `a child process exited unexpectedly with code ${child.exitCode ?? child.signalCode}`,
      );
    }
  }
}

function parseDatabaseHostPort(env: Environment): [string, number] {
  let databaseUrl =
    getEnv(env, "DATABASE_URL") ?? "jdbc:postgresql://localhost:5434/laborflow";
  if (databaseUrl.startsWith("jdbc:")) {
    databaseUrl = databaseUrl.slice(5);
  }
  try {
    const parsed = new URL(databaseUrl);
    const port = parsed.port ? Number(parsed.port) : 5434;
    if (!Number.isInteger(port) || port < 1 || port > 65_535) {
      fail(`DATABASE_URL contains an invalid TCP port: ${databaseUrl}`);
    }
    return [parsed.hostname || "localhost", port];
  } catch (error) {
    if (error instanceof LauncherError) {
      throw error;
    }
    fail(`DATABASE_URL is invalid: ${databaseUrl}`);
  }
}

function parsePort(
  env: Environment,
  name: string,
  defaultValue: number,
): number {
  const raw = getEnv(env, name) ?? String(defaultValue);
  if (!/^[+-]?\d+$/.test(raw)) {
    fail(`${name} must be a valid TCP port, got: ${raw}`);
  }
  const port = Number(raw);
  if (port < 1 || port > 65_535) {
    fail(`${name} must be between 1 and 65535, got: ${raw}`);
  }
  return port;
}

function canConnect(
  host: string,
  port: number,
  timeoutMilliseconds: number,
): Promise<boolean> {
  return new Promise((resolve) => {
    const socket = net.createConnection({ host, port });
    let settled = false;
    const finish = (connected: boolean): void => {
      if (settled) {
        return;
      }
      settled = true;
      socket.destroy();
      resolve(connected);
    };
    socket.setTimeout(timeoutMilliseconds);
    socket.once("connect", () => finish(true));
    socket.once("timeout", () => finish(false));
    socket.once("error", () => finish(false));
  });
}

async function ensurePortAvailable(
  service: string,
  host: string,
  port: number,
  envName: string,
): Promise<void> {
  if (!(await canConnect(host, port, 1_000))) {
    return;
  }
  await killProcessesOnPort(service, port);
  if (await canConnect(host, port, 1_000)) {
    fail(
      `${service} port ${port} is still in use after cleanup. Stop the existing process or set ${envName} to another port.`,
    );
  }
}

async function waitForPort(
  service: string,
  host: string,
  port: number,
  timeoutSeconds = 60,
): Promise<void> {
  log(`waiting for ${service} at ${host}:${port}`);
  const deadline = Date.now() + timeoutSeconds * 1_000;
  while (Date.now() < deadline && !shutdownRequested) {
    checkChildren();
    if (await canConnect(host, port, 2_000)) {
      log(`${service} is reachable`);
      return;
    }
    await sleep(1_000);
  }
  if (!shutdownRequested) {
    fail(`${service} is not reachable at ${host}:${port}`);
  }
}

function ensureDocker(env: Environment): void {
  if (!commandExists("docker")) {
    fail("docker is required unless --no-docker is used");
  }
  if (!fs.existsSync(path.join(COMPOSE_DIR, "docker-compose.yml"))) {
    fail(`docker-compose.yml not found in ${COMPOSE_DIR}`);
  }
  runChecked("docker", ["compose", "up", "-d"], COMPOSE_DIR, env);
}

function stopDocker(env: Environment): void {
  if (!commandExists("docker")) {
    fail("docker command not found");
  }
  if (!fs.existsSync(path.join(COMPOSE_DIR, "docker-compose.yml"))) {
    fail(`docker-compose.yml not found in ${COMPOSE_DIR}`);
  }
  runChecked("docker", ["compose", "down"], COMPOSE_DIR, env);
}

function findJavaHome(env: Environment): string {
  const configured = getEnv(env, "JAVA_HOME");
  if (configured) {
    const executable = path.join(
      configured,
      "bin",
      process.platform === "win32" ? "java.exe" : "java",
    );
    if (fs.existsSync(executable)) {
      return configured;
    }
  }
  const java = findCommand("java");
  if (java !== undefined) {
    return path.dirname(path.dirname(fs.realpathSync(java)));
  }
  fail("Java not found. Set JAVA_HOME or install JDK 21 on PATH.");
}

function findMaven(env: Environment): string {
  const configured = getEnv(env, "MAVEN_BIN");
  if (configured && fs.existsSync(configured)) {
    return configured;
  }
  const maven = findCommand("mvn");
  if (maven !== undefined) {
    return maven;
  }
  fail("Maven not found. Set MAVEN_BIN or install Maven on PATH.");
}

function ensureDesktopDependencies(env: Environment): void {
  runChecked(process.execPath, ["install", "--frozen-lockfile"], DESKTOP_DIR, env);
}

function ensureMiniappDependencies(env: Environment): void {
  if (!fs.existsSync(MINIAPP_DIR)) {
    return;
  }
  runChecked(process.execPath, ["install", "--frozen-lockfile"], MINIAPP_DIR, env);
}

function startServer(env: Environment): ChildProcess {
  const javaHome = findJavaHome(env);
  const maven = findMaven(env);
  const serverEnv = { ...env };
  setEnv(serverEnv, "JAVA_HOME", javaHome);
  setEnv(
    serverEnv,
    "PATH",
    `${path.join(javaHome, "bin")}${path.delimiter}${getEnv(serverEnv, "PATH") ?? ""}`,
  );
  if (getEnv(serverEnv, "TZ") === undefined) {
    setEnv(serverEnv, "TZ", "Asia/Shanghai");
  }
  return popenStream(
    "server",
    maven,
    ["spring-boot:run"],
    SERVER_DIR,
    serverEnv,
  );
}

function startDesktop(env: Environment): ChildProcess {
  const desktopEnv = { ...env };
  if (getEnv(desktopEnv, "VITE_API_BASE_URL") === undefined) {
    setEnv(
      desktopEnv,
      "VITE_API_BASE_URL",
      `http://localhost:${getEnv(env, "SERVER_PORT") ?? "8089"}/api`,
    );
  }
  return popenStream("desktop", process.execPath, ["run", "dev"], DESKTOP_DIR, desktopEnv);
}

function startMiniapp(env: Environment): ChildProcess {
  return popenStream("miniapp", process.execPath, ["run", "dev"], MINIAPP_DIR, env);
}

async function waitForever(miniappEnabled: boolean): Promise<void> {
  const env = mergedEnv();
  const serverPort = getEnv(env, "SERVER_PORT") ?? "8089";
  log(
    `started. Desktop renderer: http://localhost:5175  API: http://localhost:${serverPort}`,
  );
  if (miniappEnabled) {
    log(
      "miniapp watch build output: clients/miniapp/dist/ (open it in WeChat DevTools)",
    );
  }
  log("press Ctrl+C to stop server, desktop, and miniapp processes");
  while (!shutdownRequested) {
    checkChildren();
    await sleep(1_000);
  }
}

function printHelp(): void {
  console.log(`Usage: bun run.ts [options]

Start LaborFlow local development services.

Options:
  --no-docker    skip docker compose startup
  --no-miniapp   skip the Taro miniapp watch build
  --skip-install skip Bun install
  --stop         stop docker compose services and exit
  -h, --help     display this help`);
}

function parseArguments(argv: string[]): Arguments | undefined {
  const result: Arguments = {
    noDocker: false,
    noMiniapp: false,
    skipInstall: false,
    stop: false,
  };
  for (const argument of argv) {
    if (argument === "-h" || argument === "--help") {
      printHelp();
      return undefined;
    }
    if (argument === "--no-docker") {
      result.noDocker = true;
    } else if (argument === "--no-miniapp") {
      result.noMiniapp = true;
    } else if (argument === "--skip-install") {
      result.skipInstall = true;
    } else if (argument === "--stop") {
      result.stop = true;
    } else {
      fail(`unknown argument: ${argument}`);
    }
  }
  return result;
}

async function main(): Promise<void> {
  const args = parseArguments(process.argv.slice(2));
  if (args === undefined) {
    return;
  }
  ensureEnvFile();
  const env = mergedEnv();
  if (args.stop) {
    stopDocker(env);
    return;
  }
  if (!args.noDocker) {
    ensureDocker(env);
  }
  const [host, databasePort] = parseDatabaseHostPort(env);
  await waitForPort("PostgreSQL", host, databasePort);
  const serverPort = parsePort(env, "SERVER_PORT", 8089);
  const desktopPort = 5175;
  managedPorts.add(serverPort);
  managedPorts.add(desktopPort);
  await ensurePortAvailable("API", "localhost", serverPort, "SERVER_PORT");
  await ensurePortAvailable(
    "Desktop renderer",
    "localhost",
    desktopPort,
    "desktop Vite port",
  );
  if (!args.skipInstall) {
    ensureDesktopDependencies(env);
    if (!args.noMiniapp) {
      ensureMiniappDependencies(env);
    }
  }
  startServer(env);
  startDesktop(env);
  if (!args.noMiniapp) {
    startMiniapp(env);
  }
  await waitForPort("API", "localhost", serverPort);
  await waitForPort("Desktop renderer", "localhost", desktopPort);
  await waitForever(!args.noMiniapp);
}

for (const signal of ["SIGINT", "SIGTERM"] as const) {
  process.on(signal, () => {
    if (shutdownRequested) {
      return;
    }
    shutdownRequested = true;
    log("stopping...");
    void stopChildren().then(() => process.exit(0));
  });
}

void (async () => {
  try {
    await main();
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`[run] ERROR: ${message}`);
    process.exitCode = 1;
  } finally {
    await stopChildren();
  }
})();
